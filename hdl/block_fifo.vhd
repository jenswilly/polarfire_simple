-- Block FIFO: valid/ready wrapper around the CoreFIFO configuration BLOCK_FIFO_CORE
--
--   s_* (blocks in) --> BLOCK_FIFO_CORE (single clock, FWFT) --> m_* (blocks out)
--
--   One FIFO word is one complete block (BLOCK_BYTES bytes). The wrapper only maps
--   valid/ready onto CoreFIFO's WE/RE/FULL/EMPTY:
--     s_ready = not FULL,  WE = s_valid and s_ready
--     m_valid = not EMPTY, RE = m_valid and m_ready
--   With FWFT the head of the FIFO is on Q whenever EMPTY is low, so m_data is valid
--   together with m_valid without a read first.
--
-- BLOCK_FIFO_CORE must be configured in Libero to match:
--   Single Clock, Sync Reset, FWFT, width BLOCK_BYTES * 8 on both ports, active-high
--   WE/RE, "Disable Reads when FIFO is Empty" and "Disable Writes when FIFO is Full".
--   BLOCK_BYTES here is only checked, it does not change the core.

library ieee;
use ieee.std_logic_1164.all;

entity block_fifo is
    generic (
        BLOCK_BYTES : positive := 10       -- Must match the CoreFIFO width / 8
    );
    port (
        clk      : in  std_logic;
        reset_n  : in  std_logic;           -- Synchronous, active low

        -- Blocks in
        s_data   : in  std_logic_vector(BLOCK_BYTES * 8 - 1 downto 0);
        s_valid  : in  std_logic;
        s_ready  : out std_logic;

        -- Blocks out
        m_data   : out std_logic_vector(BLOCK_BYTES * 8 - 1 downto 0);
        m_valid  : out std_logic;
        m_ready  : in  std_logic
    );
end entity block_fifo;

architecture rtl of block_fifo is

    -- Generated by Libero (Verilog); only the ports enabled in the configuration
    component BLOCK_FIFO_CORE is
        port (
            CLK     : in  std_logic;
            RESET_N : in  std_logic;
            DATA    : in  std_logic_vector(79 downto 0);
            WE      : in  std_logic;
            RE      : in  std_logic;
            Q       : out std_logic_vector(79 downto 0);
            FULL    : out std_logic;
            EMPTY   : out std_logic
        );
    end component;

    signal full  : std_logic;
    signal empty : std_logic;

begin

    assert BLOCK_BYTES * 8 = 80
        report "block_fifo: BLOCK_BYTES does not match the BLOCK_FIFO_CORE width (80 bits)"
        severity failure;

    u_core : BLOCK_FIFO_CORE
        port map (
            CLK     => clk,
            RESET_N => reset_n,
            DATA    => s_data,
            WE      => s_valid and not full,
            RE      => m_ready and not empty,
            Q       => m_data,
            FULL    => full,
            EMPTY   => empty
        );

    s_ready <= not full;
    m_valid <= not empty;

end architecture rtl;
